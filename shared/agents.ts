export type CustomizationField = {
  key: string;
  label: string;
  type: "toggle" | "select" | "slider" | "text" | "textarea" | "number";
  default: unknown;
  options?: string[];
  min?: number;
  max?: number;
  step?: number;
  placeholder?: string;
  description?: string;
};

export type Beast = {
  slug: string;
  name: string;
  tagline: string;
  description: string;
  category: string;
  platform: string;
  oauthProvider?: string;
  requiresOAuth: boolean;
  scopes?: string[];
  capabilities: string[];
  permissions: string[];
  customizations: CustomizationField[];
  rating: number;
  installs: number;
  featured: boolean;
  hot: boolean;
  new: boolean;
  accentColor: string;
  actions: string[];
  /**
   * Persona config for the live runtime. When present, the beast uses the LLM
   * tool-use engine; when absent, the beast falls through to demo-mode runs.
   */
  systemPrompt?: string;
  /** Fully-qualified tool names the beast is allowed to call (e.g. "github.list_repos"). */
  tools?: string[];
  /** Optional suggested first messages rendered in the chat empty state. */
  suggestedPrompts?: string[];
};

